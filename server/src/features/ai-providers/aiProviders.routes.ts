import { Router } from 'express';
import { z } from 'zod';
import { requireAuth } from '../../middleware/auth.js';
import { validate } from '../../middleware/validate.js';
import { create, list, remove } from './aiProviders.controller.js';
export const aiProvidersRoutes = Router();
const id = z.object({ id: z.string().regex(/^[a-f\d]{24}$/i) });
const provider = z.object({ label: z.string().min(1).max(80), baseUrl: z.string().url(), apiKey: z.string().max(1000).optional(), model: z.string().min(1).max(120) });
aiProvidersRoutes.use(requireAuth);
aiProvidersRoutes.get('/', list);
aiProvidersRoutes.post('/', validate({ body: provider }), create);
aiProvidersRoutes.delete('/:id', validate({ params: id }), remove);
